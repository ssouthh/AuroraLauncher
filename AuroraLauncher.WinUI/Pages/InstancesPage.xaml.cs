    private bool _isAutoGeneratedName = true;

    private async Task LoadGameVersionsAsync()
    {
        VersionsLoadingRing.IsActive = true;
        VersionsLoadingRing.Visibility = Visibility.Visible;
        VersionsLoadingText.Visibility = Visibility.Visible;
        VersionsLoadingText.Text = "Загрузка списка версий с Mojang...";

        try
        {
            var manifest = await Mojang.GetManifestAsync(ct: CancellationToken.None);
            var versions = manifest.Arr("versions")
                .Where(v =>
                {
                    var id = v.Str("id") ?? "";
                    var type = v.Str("type") ?? "";
                    if (!Ctx.Settings.ShowSnapshots && type != "release") return false;
                    if (!Ctx.Settings.ShowOldVersions)
                    {
                        var m = System.Text.RegularExpressions.Regex.Match(id, @"^1\.(\d+)");
                        if (m.Success)
                        {
                            var minor = int.Parse(m.Groups[1].Value);
                            if (minor < 12) return false;
                        }
                    }
                    return true;
                })
                .Select(v => v.Str("id")!)
                .Where(v => !string.IsNullOrEmpty(v))
                .ToList();

            GameVersionComboBox.ItemsSource = versions;
            var latestRelease = manifest.El("latest")?.Str("release");
            var def = (!string.IsNullOrEmpty(latestRelease) && versions.Contains(latestRelease))
                ? latestRelease
                : versions.FirstOrDefault();
            GameVersionComboBox.SelectedItem = def;

            VersionsLoadingRing.IsActive = false;
            VersionsLoadingRing.Visibility = Visibility.Collapsed;
            VersionsLoadingText.Text = $"Доступно {versions.Count} версий игры";

            UpdateSuggestedInstanceName();
        }
        catch (Exception ex)
        {
            VersionsLoadingRing.IsActive = false;
            VersionsLoadingRing.Visibility = Visibility.Collapsed;
            VersionsLoadingText.Text = "Ошибка загрузки манифеста: " + ex.Message;
        }
    }

    private async void GameVersionComboBox_SelectionChanged(object sender, SelectionChangedEventArgs e)
    {
        UpdateSuggestedInstanceName();
        await RefreshLoaderVersionsAsync();
    }

    private async void LoaderKindComboBox_SelectionChanged(object sender, SelectionChangedEventArgs e)
    {
        UpdateSuggestedInstanceName();
        await RefreshLoaderVersionsAsync();
    }

    private void UpdateSuggestedInstanceName()
    {
        if (GameVersionComboBox.SelectedItem is not string mcVersion) return;
        var selectedIdx = Math.Max(0, LoaderKindComboBox.SelectedIndex);
        var kind = Loaders.Supported[selectedIdx].Id;

        var prefix = kind switch
        {
            "fabric" => "Fabric",
            "forge" => "Forge",
            "neoforge" => "NeoForge",
            "quilt" => "Quilt",
            _ => "Vanilla"
        };

        var baseName = $"{prefix} {mcVersion}";
        var candidate = baseName;
        var counter = 2;
        while (LauncherState.InstancesList.Any(i => i.Name.Equals(candidate, StringComparison.OrdinalIgnoreCase)))
        {
            candidate = $"{baseName} ({counter++})";
        }

        if (string.IsNullOrWhiteSpace(InstanceNameTextBox.Text) || _isAutoGeneratedName)
        {
            _isAutoGeneratedName = true;
            InstanceNameTextBox.Text = candidate;
        }
    }

    private async Task RefreshLoaderVersionsAsync()
    {
        LoaderVersionComboBox.Items.Clear();
        LoaderVersionComboBox.Items.Add("Последняя рекомендуемая");
        LoaderVersionComboBox.SelectedIndex = 0;

        var selectedIdx = Math.Max(0, LoaderKindComboBox.SelectedIndex);
        var kind = Loaders.Supported[selectedIdx].Id;

        // При ванильном Minecraft скрываем выбор версии загрузчика и показываем информационный баннер
        LoaderVersionPanel.Visibility = (kind == "vanilla") ? Visibility.Collapsed : Visibility.Visible;
        VanillaInfoBorder.Visibility = (kind == "vanilla") ? Visibility.Visible : Visibility.Collapsed;

        if (kind == "vanilla") return;
        if (GameVersionComboBox.SelectedItem is not string mcVersion) return;

        try
        {
            var versions = kind switch
            {
                "fabric" => await Loaders.FabricVersionsForAsync(mcVersion, CancellationToken.None),
                "forge" => await Loaders.ForgePromosAsync(mcVersion, CancellationToken.None),
                "neoforge" => await Loaders.NeoForgeVersionsForAsync(mcVersion, CancellationToken.None),
                _ => new List<string>()
            };

            foreach (var v in versions)
            {
                LoaderVersionComboBox.Items.Add(v);
            }
        }
        catch
        {
            // Не критично, если список версий конкретного загрузчика для этой версии недоступен
        }
    }

    private async void CreateInstanceButton_Click(object sender, RoutedEventArgs e)
    {
        var rawName = InstanceNameTextBox.Text?.Trim() ?? "";
        if (string.IsNullOrWhiteSpace(rawName))
        {
            ShowInfo("Введите название сборки.", InfoBarSeverity.Warning);
            return;
        }

        var cleanName = string.Concat(rawName.Select(c => System.IO.Path.GetInvalidFileNameChars().Contains(c) ? '_' : c));
        if (LauncherState.InstancesList.Any(i => i.Name.Equals(cleanName, StringComparison.OrdinalIgnoreCase)))
        {
            ShowInfo("Сборка с таким названием уже существует.", InfoBarSeverity.Warning);
            return;
        }

        if (GameVersionComboBox.SelectedItem is not string mcVersion)
        {
            ShowInfo("Выберите версию Minecraft.", InfoBarSeverity.Warning);
            return;
        }

        var loaderIdx = Math.Max(0, LoaderKindComboBox.SelectedIndex);
        var loaderKind = Loaders.Supported[loaderIdx].Id;
        var loaderVer = LoaderVersionComboBox.SelectedIndex > 0 ? LoaderVersionComboBox.SelectedItem?.ToString() ?? "" : "";

        var instance = new Instance
        {
            Name = cleanName,
            McVersion = mcVersion,
            Loader = loaderKind,
            LoaderVersion = loaderVer
        };

        _createCts?.Cancel();
        _createCts = new CancellationTokenSource();

        CreateInstanceButton.IsEnabled = false;
        CreationProgressSection.Visibility = Visibility.Visible;
        CreationProgressBar.IsIndeterminate = true;
        CreationStatusText.Text = $"Подготовка сборки {instance.Name}...";

        try
        {
            var progress = new Progress<ProgressReport>(p =>
            {
                DispatcherQueue.TryEnqueue(() =>
                {
                    CreationStatusText.Text = string.IsNullOrWhiteSpace(p.Detail) ? p.Phase : $"{p.Phase} · {p.Detail}";
                    if (p.Percent >= 0)
                    {
                        CreationProgressBar.IsIndeterminate = false;
                        CreationProgressBar.Value = p.Percent;
                        CreationPercentText.Text = $"{p.Percent}%";
                    }
                    else
                    {
                        CreationProgressBar.IsIndeterminate = true;
                        CreationPercentText.Text = "";
                    }
                });
            });

            await Instances.PrepareAsync(instance, progress, _createCts.Token);

            var all = LauncherState.InstancesList;
            all.Insert(0, instance);
            Instances.SaveAll(all);
            LauncherState.SelectInstance(instance);
            LauncherState.RefreshInstances();

            RefreshAllInstancesList();
            ShowInfo($"Сборка \"{instance.Name}\" успешно создана и готова к игре!", InfoBarSeverity.Success);
            _isAutoGeneratedName = true;
            UpdateSuggestedInstanceName();
        }
        catch (OperationCanceledException)
        {
            ShowInfo("Создание сборки отменено.", InfoBarSeverity.Informational);
        }
        catch (Exception ex)
        {
            ShowInfo("Ошибка при создании сборки: " + ex.Message, InfoBarSeverity.Error);
        }
        finally
        {
            CreateInstanceButton.IsEnabled = true;
            CreationProgressSection.Visibility = Visibility.Collapsed;
        }
    }

    private void RefreshAllInstancesList()
    {
        AllInstancesPanel.Children.Clear();
        var list = LauncherState.InstancesList;
        InstancesCountHeader.Text = $"{list.Count} сборок";

        if (list.Count == 0)
        {
            AllInstancesPanel.Children.Add(new TextBlock
            {
                Text = "У вас пока нет созданных сборок.",
                Foreground = (Brush)Application.Current.Resources["TextFillColorSecondaryBrush"]
            });
            return;
        }

        foreach (var inst in list)
        {
            var card = new Border
            {
                Background = (Brush)Application.Current.Resources["CardBackgroundFillColorDefaultBrush"],
                BorderBrush = (Brush)Application.Current.Resources["CardStrokeColorDefaultBrush"],
                BorderThickness = new Thickness(1),
                CornerRadius = new CornerRadius(8),
                Padding = new Thickness(16, 12, 16, 12)
            };

            var grid = new Grid();
            grid.ColumnDefinitions.Add(new ColumnDefinition { Width = GridLength.Auto });
            grid.ColumnDefinitions.Add(new ColumnDefinition { Width = new GridLength(1, GridUnitType.Star) });
            grid.ColumnDefinitions.Add(new ColumnDefinition { Width = GridLength.Auto });

            var iconBorder = new Border
            {
                Width = 40,
                Height = 40,
                CornerRadius = new CornerRadius(6),
                Background = (Brush)Application.Current.Resources["LayerFillColorDefaultBrush"],
                Margin = new Thickness(0, 0, 16, 0)
            };
            var iconText = new TextBlock
            {
                Text = inst.Icon,
                FontSize = 20,
                HorizontalAlignment = HorizontalAlignment.Center,
                VerticalAlignment = VerticalAlignment.Center
            };
            iconBorder.Child = iconText;
            Grid.SetColumn(iconBorder, 0);
            grid.Children.Add(iconBorder);

            var textPanel = new StackPanel { VerticalAlignment = VerticalAlignment.Center, Spacing = 2 };
            textPanel.Children.Add(new TextBlock
            {
                Text = inst.Name,
                Style = (Style)Application.Current.Resources["BodyStrongTextBlockStyle"]
            });
            textPanel.Children.Add(new TextBlock
            {
                Text = inst.Subtitle,
                Style = (Style)Application.Current.Resources["CaptionTextBlockStyle"],
                Foreground = (Brush)Application.Current.Resources["TextFillColorSecondaryBrush"]
            });
            Grid.SetColumn(textPanel, 1);
            grid.Children.Add(textPanel);

            var actionsPanel = new StackPanel { Orientation = Orientation.Horizontal, Spacing = 8, VerticalAlignment = VerticalAlignment.Center };

            var isSelected = LauncherState.SelectedInstance?.Name == inst.Name;
            var selectBtn = new Button
            {
                Content = isSelected ? I18n.Get("Java.ActiveBadge") : I18n.Get("Java.SetActive"),
                IsEnabled = !isSelected,
                Style = isSelected ? (Style)Application.Current.Resources["AccentButtonStyle"] : (Style)Application.Current.Resources["DefaultButtonStyle"]
            };
            selectBtn.Click += (_, _) =>
            {
                LauncherState.SelectInstance(inst);
                RefreshAllInstancesList();
            };
            actionsPanel.Children.Add(selectBtn);

            var exportBtn = new Button
            {
                Content = new FontIcon { Glyph = "\uEDE1", FontSize = 14 }
            };
            ToolTipService.SetToolTip(exportBtn, I18n.Get("Instances.Export"));
            exportBtn.Click += async (_, _) =>
            {
                try
                {
                    var picker = new Windows.Storage.Pickers.FileSavePicker();
                    var hwnd = WinRT.Interop.WindowNative.GetWindowHandle(App.CurrentWindow);
                    WinRT.Interop.InitializeWithWindow.Initialize(picker, hwnd);
                    picker.SuggestedStartLocation = Windows.Storage.Pickers.PickerLocationId.Desktop;
                    picker.FileTypeChoices.Add("Aurora Build (*.albuild)", new List<string>() { ".albuild" });
                    picker.SuggestedFileName = $"{inst.Name}.albuild";
                    var file = await picker.PickSaveFileAsync();
                    if (file == null) return;

                    ShowInfo($"Exporting \"{inst.Name}\"...", InfoBarSeverity.Informational);
                    var progress = new Progress<string>(s => ShowInfo(s, InfoBarSeverity.Informational));
                    await BuildPackageManager.ExportBuildAsync(inst, file.Path, progress, CancellationToken.None);
                    ShowInfo(I18n.Get("Instances.ExportSuccess", file.Name), InfoBarSeverity.Success);
                }
                catch (Exception ex)
                {
                    ShowInfo(I18n.Get("Common.Error") + ": " + ex.Message, InfoBarSeverity.Error);
                }
            };
            actionsPanel.Children.Add(exportBtn);

            var modsBtn = new Button
            {
                Content = new FontIcon { Glyph = "\uE896", FontSize = 14 }
            };
            ToolTipService.SetToolTip(modsBtn, I18n.Get("Home.Mods"));
            modsBtn.Click += (_, _) =>
            {
                LauncherState.SelectInstance(inst);
                (App.CurrentWindow as MainWindow)?.NavigateTo("mods");
            };
            actionsPanel.Children.Add(modsBtn);

            var folderBtn = new Button
            {
                Content = new FontIcon { Glyph = "\uED25", FontSize = 14 }
            };
            ToolTipService.SetToolTip(folderBtn, I18n.Get("Home.GameFolder"));
            folderBtn.Click += (_, _) => Instances.OpenFolder(inst);
            actionsPanel.Children.Add(folderBtn);

            var deleteBtn = new Button
            {
                Content = new FontIcon { Glyph = "\uE74D", FontSize = 14 }
            };
            ToolTipService.SetToolTip(deleteBtn, I18n.Get("Common.Delete"));
            deleteBtn.Click += async (_, _) =>
            {
                var dialog = new ContentDialog
                {
                    XamlRoot = XamlRoot,
                    Title = I18n.Get("Instances.DeleteConfirmTitle"),
                    Content = I18n.Get("Instances.DeleteConfirmMessage", inst.Name),
                    PrimaryButtonText = I18n.Get("Common.Delete"),
                    CloseButtonText = I18n.Get("Common.Cancel")
                };
                if (await dialog.ShowAsync() == ContentDialogResult.Primary)
                {
                    Instances.Delete(inst);
                    var all = LauncherState.InstancesList;
                    all.RemoveAll(i => i.Name == inst.Name);
                    Instances.SaveAll(all);
                    LauncherState.RefreshInstances();
                    RefreshAllInstancesList();
                }
            };
            actionsPanel.Children.Add(deleteBtn);

            Grid.SetColumn(actionsPanel, 2);
            grid.Children.Add(actionsPanel);

            card.Child = grid;
            AllInstancesPanel.Children.Add(card);
        }
    }

    private async void ImportBuildBtn_Click(object sender, RoutedEventArgs e)
    {
        try
        {
            var picker = new Windows.Storage.Pickers.FileOpenPicker();
            var hwnd = WinRT.Interop.WindowNative.GetWindowHandle(App.CurrentWindow);
            WinRT.Interop.InitializeWithWindow.Initialize(picker, hwnd);
            picker.FileTypeFilter.Add(".albuild");
            picker.FileTypeFilter.Add(".zip");
            var file = await picker.PickSingleFileAsync();
            if (file == null) return;

            ShowInfo($"Importing {file.Name}...", InfoBarSeverity.Informational);
            var progress = new Progress<string>(s => ShowInfo(s, InfoBarSeverity.Informational));
            var inst = await BuildPackageManager.ImportBuildAsync(file.Path, null, progress, CancellationToken.None);

            LauncherState.RefreshInstances();
            LauncherState.SelectInstance(inst);
            RefreshAllInstancesList();
            ShowInfo(I18n.Get("Instances.ImportSuccess", inst.Name), InfoBarSeverity.Success);
        }
        catch (Exception ex)
        {
            ShowInfo(I18n.Get("Common.Error") + ": " + ex.Message, InfoBarSeverity.Error);
        }
    }

    private void CleanStorageBtn_Click(object sender, RoutedEventArgs e)
    {
        var inst = LauncherState.SelectedInstance;
        if (inst == null)
        {
            ShowInfo(I18n.Get("Mods.SelectInstanceFirst"), InfoBarSeverity.Warning);
            return;
        }

        var (files, mb) = BuildPackageManager.CleanInstanceStorage(inst);
        ShowInfo(I18n.Get("Instances.StorageCleaned", files, $"{mb:0.1}"), InfoBarSeverity.Success);
    }

    private void ShowInfo(string message, InfoBarSeverity severity)
    {
        InstancesInfoBar.Message = message;
        InstancesInfoBar.Severity = severity;
        InstancesInfoBar.IsOpen = true;
    }
}
