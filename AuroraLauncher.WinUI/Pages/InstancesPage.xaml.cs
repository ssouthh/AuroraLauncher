public sealed partial class InstancesPage : Page
{
    private CancellationTokenSource? _createCts;

    public InstancesPage()
    {
        InitializeComponent();
        Loaded += InstancesPage_Loaded;
        Unloaded += InstancesPage_Unloaded;
    }

    private async void InstancesPage_Loaded(object sender, RoutedEventArgs e)
    {
        I18n.LanguageChanged += OnLanguageChanged;
        ApplyLocalization();

        LoaderKindComboBox.ItemsSource = Loaders.Supported.Select(l => l.Title).ToList();
        LoaderKindComboBox.SelectedIndex = 0; // Vanilla

        InstanceNameTextBox.TextChanged += (_, _) =>
        {
            if (InstanceNameTextBox.FocusState != FocusState.Unfocused)
                _isAutoGeneratedName = false;
        };

        RefreshAllInstancesList();
        await LoadGameVersionsAsync();
    }

    private void InstancesPage_Unloaded(object sender, RoutedEventArgs e)
    {
        I18n.LanguageChanged -= OnLanguageChanged;
    }

    private void OnLanguageChanged()
    {
        DispatcherQueue?.TryEnqueue(() =>
        {
            ApplyLocalization();
            RefreshAllInstancesList();
        });
    }

